export function icon(name, { size = 16 } = {}) {
  const svg = document.createElementNS(NS, "svg");
  for (const [k, v] of Object.entries({
    width: size, height: size, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor",
    "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round",
    "aria-hidden": "true", focusable: "false",
  })) svg.setAttribute(k, v);
  svg.classList.add("icon");
  svg.innerHTML = PATHS[name] || PATHS.info; // PATHS is static, trusted markup
  return svg;
}

/** Replace every <span data-icon="name" data-size="16"> placeholder with its SVG. */
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((node) => {
    node.replaceChildren(icon(node.dataset.icon, { size: Number(node.dataset.size) || 16 }));
  });
}
